import assert from 'node:assert/strict';
import { deduplicatePendingRead, clearSearchCache } from '../src/services/searchCache.js';
clearSearchCache();
let calls = 0;
let resolve;
const loader = () => { calls += 1; return new Promise(done => { resolve = done; }); };
const first = deduplicatePendingRead('user1/orders/page0', loader);
const second = deduplicatePendingRead('user1/orders/page0', loader);
assert.equal(first, second);
await Promise.resolve();
assert.equal(calls, 1);
resolve({ revision: 1 });
assert.deepEqual(await first, { revision: 1 });
assert.deepEqual(await second, { revision: 1 });
assert.deepEqual(await deduplicatePendingRead('user1/orders/page0', async () => { calls += 1; return { revision: 2 }; }), { revision: 2 });
assert.equal(calls, 2);
await assert.rejects(deduplicatePendingRead('user2/orders/page0', async () => { throw new Error('Offline'); }));
assert.deepEqual(await deduplicatePendingRead('user2/orders/page0', async () => []), []);
console.log('Workflow read dedup: 8 assertions passed; simultaneous reads merge, Refresh stays fresh, failures remain retryable.');
