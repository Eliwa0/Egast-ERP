import StandardDropdown from '../components/ui/StandardDropdown';
import React from 'react';
import PageHeader from '../components/ui/PageHeader';
import { useI18n } from '../contexts/I18nContext';
import { useToast } from '../components/ui/ToastProvider';
import SearchableSelect from '../components/ui/SearchableSelect';
import { useQualityCriteriaManagement } from '../hooks/useQualityCriteriaManagement';

function fieldError(errors, field) {
  const value = errors?.[field];
  if (Array.isArray(value)) return value.join(' ');
  return value || '';
}

function QualityCriterionDialog({ open, editingCriterion, form, errors, saving, stages, stagesLoading, categories, categoriesLoading, onChange, onClose, onSubmit, t }) {
  if (!open) return null;
  return (
    <div className="simple-modal-backdrop" role="presentation">
      <div className="simple-modal-card quality-criterion-dialog" role="dialog" aria-modal="true" aria-labelledby="quality-criterion-dialog-title">
        <div className="simple-modal__header">
          <h2 id="quality-criterion-dialog-title" className="simple-modal__title">
            {editingCriterion ? t('qualityCriteria.editCriterion') : t('qualityCriteria.addCriterion')}
          </h2>
          <button type="button" className="simple-modal__close" onClick={onClose} aria-label={t('common.close')}>
            x
          </button>
        </div>
        <form className="um-modal-form quality-criterion-dialog__form" onSubmit={onSubmit}>
          <div className="form-field">
            <label className="form-label" htmlFor="criterion-code">{t('qualityCriteria.code')}</label>
            <input
              id="criterion-code"
              className="app-input"
              value={editingCriterion ? form.code : t('qualityCriteria.autoGeneratedCode')}
              readOnly
              disabled
            />
          </div>
          <div className="form-field">
            <label className="form-label" htmlFor="criterion-name-ar">{t('qualityCriteria.nameAr')}</label>
            <input
              id="criterion-name-ar"
              className={`app-input ${fieldError(errors, 'name_ar') ? 'app-input--invalid' : ''}`}
              value={form.name_ar}
              onChange={(event) => onChange('name_ar', event.target.value)}
              required
            />
            {fieldError(errors, 'name_ar') && <span className="error-msg">{fieldError(errors, 'name_ar')}</span>}
          </div>
          <div className="form-field">
            <label className="form-label" htmlFor="criterion-calculation-key">{t('qualityCriteria.calculationKey')}</label>
            <input
              id="criterion-calculation-key"
              className={`app-input ${fieldError(errors, 'calculation_key') ? 'app-input--invalid' : ''}`}
              value={form.calculation_key}
              onChange={(event) => onChange('calculation_key', event.target.value)}
              required={form.is_active}
            />
            {fieldError(errors, 'calculation_key') && <span className="error-msg">{fieldError(errors, 'calculation_key')}</span>}
          </div>
          <div className="form-field">
            <label className="form-label" htmlFor="criterion-name-en">{t('qualityCriteria.nameEn')}</label>
            <input
              id="criterion-name-en"
              className={`app-input ${fieldError(errors, 'name_en') ? 'app-input--invalid' : ''}`}
              value={form.name_en}
              onChange={(event) => onChange('name_en', event.target.value)}
            />
            {fieldError(errors, 'name_en') && <span className="error-msg">{fieldError(errors, 'name_en')}</span>}
          </div>
          <div className="quality-criterion-dialog__grid-row">
            <div className="form-field">
              <label className="form-label" htmlFor="criterion-stage">{t('qualityCriteria.inspectionStage')}</label>
              <StandardDropdown
                id="criterion-stage"
                className={`app-input ${fieldError(errors, 'inspection_stage') ? 'app-input--invalid' : ''}`}
                value={form.inspection_stage}
                onChange={(event) => onChange('inspection_stage', event.target.value)}
                required
                disabled={stagesLoading}
                placeholder={t('common.selectOption')}
              >
                <option value="">{stagesLoading ? t('common.loading') : t('common.selectOption')}</option>
                {stages.map((stage) => (
                  <option key={stage.id} value={stage.id}>
                    {stage.name_ar || stage.name_en} ({stage.code})
                  </option>
                ))}
              </StandardDropdown>
              {fieldError(errors, 'inspection_stage') && <span className="error-msg">{fieldError(errors, 'inspection_stage')}</span>}
            </div>
            <div className="form-field">
              <label className="form-label" htmlFor="criterion-category">{t('qualityCriteria.category')}</label>
              <SearchableSelect
                id="criterion-category"
                className={`app-input ${fieldError(errors, 'category') ? 'app-input--invalid' : ''}`}
                value={form.category}
                onChange={(event) => onChange('category', event.target.value)}
                required
                disabled={categoriesLoading}
                placeholder={t('common.selectOption')}
              >
                <option value="">{categoriesLoading ? t('common.loading') : t('common.selectOption')}</option>
                {categories.map((category) => (
                  <option key={category.id} value={category.id}>
                    {category.name_ar || category.name_en} ({category.code})
                  </option>
                ))}
              </SearchableSelect>
              {fieldError(errors, 'category') && <span className="error-msg">{fieldError(errors, 'category')}</span>}
            </div>
          </div>
          <div className="quality-criterion-dialog__grid-row quality-criterion-dialog__grid-row--compact">
            <div className="form-field">
              <label className="form-label" htmlFor="criterion-order">{t('qualityCriteria.displayOrder')}</label>
              <input
                id="criterion-order"
                className="app-input"
                type="number"
                value={form.display_order}
                onChange={(event) => onChange('display_order', event.target.value)}
              />
            </div>
            <label className="form-field quality-criterion-dialog__active-toggle">
              <input
                type="checkbox"
                checked={form.is_active}
                onChange={(event) => onChange('is_active', event.target.checked)}
              />
              <span>{t('qualityCriteria.active')}</span>
            </label>
          </div>
          {fieldError(errors, 'non_field_errors') && <div className="feedback-message feedback-message--error">{fieldError(errors, 'non_field_errors')}</div>}
          <div className="modal-btn-row quality-criterion-dialog__actions">
            <button type="button" className="app-button app-button--secondary" onClick={onClose}>
              {t('common.cancel')}
            </button>
            <button type="submit" className="app-button app-button--primary" disabled={saving}>
              {saving ? t('common.working') : t('common.save')}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}

function QualityCriteriaManagementPage() {
  const { t } = useI18n();
  const toast = useToast();
  const controller = useQualityCriteriaManagement(toast, t);

  return (
    <div className="page-shell page-shell--padded-lg">
      <PageHeader
        eyebrow={t('qualityCriteria.eyebrow')}
        title={t('qualityCriteria.title')}
        description={t('qualityCriteria.description')}
      />

      <div className="rules-page-shell">
        <section className="card-panel">
          <div style={{ display: 'flex', justifyContent: 'space-between', gap: '12px', alignItems: 'center', flexWrap: 'wrap' }}>
            <div className="rr-stats-row" style={{ flex: '1 1 320px', margin: 0 }}>
              <div className="rr-stat-chip">
                <span className="rr-stat-chip__value">{controller.criteria.length}</span>
                <span className="rr-stat-chip__label">{t('qualityCriteria.total')}</span>
              </div>
              <div className="rr-stat-chip">
                <span className="rr-stat-chip__value" style={{ color: 'var(--success)' }}>{controller.activeCount}</span>
                <span className="rr-stat-chip__label">{t('qualityCriteria.active')}</span>
              </div>
            </div>
            <button type="button" className="app-button app-button--primary" onClick={controller.openCreateDialog}>
              + {t('qualityCriteria.addCriterion')}
            </button>
          </div>
        </section>

        <section className="card-panel rules-panel">
          <form
            className="rules-panel__lookup-form quality-criteria-filter-toolbar"
            onSubmit={(event) => {
              event.preventDefault();
            }}
          >
            <StandardDropdown
              className="app-input quality-criteria-filter-toolbar__category"
              value={controller.selectedStageId}
              onChange={(event) => controller.setSelectedStageId(event.target.value)}
              disabled={controller.stagesLoading}
              aria-label={t('qualityCriteria.stageFilter')}
              placeholder={t('qualityCriteria.allStages')}
            >
              <option value="">{controller.stagesLoading ? t('common.loading') : t('qualityCriteria.allStages')}</option>
              {controller.stages.map((stage) => (
                <option key={stage.id} value={String(stage.id)}>
                  {stage.name_ar || stage.name_en || stage.code}
                </option>
              ))}
            </StandardDropdown>
            <SearchableSelect
              className="app-input quality-criteria-filter-toolbar__category"
              value={controller.selectedCategoryId}
              onChange={(event) => controller.setSelectedCategoryId(event.target.value)}
              disabled={controller.categoriesLoading}
              aria-label={t('qualityCriteria.categoryFilter')}
              placeholder={t('qualityCriteria.allCategories')}
            >
              <option value="">{controller.categoriesLoading ? t('common.loading') : t('qualityCriteria.allCategories')}</option>
              {controller.categories.map((category) => (
                <option key={category.id} value={String(category.id)}>
                  {category.name_ar || category.name_en || category.code}
                </option>
              ))}
            </SearchableSelect>
            <input
              className="app-input quality-criteria-filter-toolbar__search"
              type="search"
              value={controller.search}
              onChange={(event) => controller.setSearch(event.target.value)}
              placeholder={t('qualityCriteria.searchPlaceholder')}
            />
          </form>

          <div className="table-scroll-wrap">
            <table className="data-table management-table">
              <thead>
                <tr>
                  <th>{t('qualityCriteria.code')}</th>
                  <th>{t('qualityCriteria.calculationKey')}</th>
                  <th>{t('qualityCriteria.nameAr')}</th>
                  <th>{t('qualityCriteria.nameEn')}</th>
                  <th>{t('qualityCriteria.inspectionStage')}</th>
                  <th>{t('qualityCriteria.category')}</th>
                  <th>{t('qualityCriteria.displayOrder')}</th>
                  <th>{t('qualityCriteria.status')}</th>
                  <th>{t('qualityCriteria.actions')}</th>
                </tr>
              </thead>
              <tbody>
                {controller.loading ? (
                  <tr><td colSpan="9">{t('common.loading')}</td></tr>
                ) : controller.criteria.length === 0 ? (
                  <tr><td colSpan="9">{t('common.noData')}</td></tr>
                ) : controller.filteredCriteria.length === 0 ? (
                  <tr><td colSpan="9">{t('qualityCriteria.noCriteriaMatch')}</td></tr>
                ) : controller.filteredCriteria.map((criterion) => (
                  <tr key={criterion.id}>
                    <td><strong>{criterion.code}</strong></td>
                    <td>{criterion.calculation_key}</td>
                    <td>{criterion.name_ar}</td>
                    <td>{criterion.name_en}</td>
                    <td>{criterion.inspection_stage_detail?.name_ar || criterion.inspection_stage_name_ar || criterion.inspection_stage_code}</td>
                    <td>{criterion.category_detail?.name_ar || criterion.category_name_ar || criterion.category_code}</td>
                    <td>{criterion.display_order}</td>
                    <td>{criterion.is_active ? t('qualityCriteria.enabled') : t('qualityCriteria.disabled')}</td>
                    <td>
                      <div className="management-table__actions">
                        <button type="button" className="app-button app-button--secondary app-button--compact" onClick={() => controller.openEditDialog(criterion)}>
                          {t('common.edit')}
                        </button>
                        <button type="button" className="app-button app-button--secondary app-button--compact" onClick={() => controller.toggleCriterion(criterion)}>
                          {criterion.is_active ? t('qualityCriteria.disable') : t('qualityCriteria.enable')}
                        </button>
                        <button type="button" className="app-button app-button--danger app-button--compact" onClick={() => controller.deleteCriterion(criterion)}>
                          {t('common.delete')}
                        </button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </section>
      </div>

      <QualityCriterionDialog
        open={controller.dialogOpen}
        editingCriterion={controller.editingCriterion}
        form={controller.form}
        errors={controller.errors}
        saving={controller.saving}
        stages={controller.stages}
        stagesLoading={controller.stagesLoading}
        categories={controller.categories}
        categoriesLoading={controller.categoriesLoading}
        onChange={controller.updateForm}
        onClose={controller.closeDialog}
        onSubmit={controller.saveCriterion}
        t={t}
      />
    </div>
  );
}

export default QualityCriteriaManagementPage;
